## 방법

1. 검색창에 만들 문서 제목을 입력하고 검색합니다.
2. 결과가 없으면 **문서 만들기** 버튼이 나타납니다. 또는 다른 문서에서 빨간 링크를 눌러도 됩니다.
3. 내용을 쓰고 **저장**을 누릅니다. 바로 문서가 만들어집니다.

제목에 `/` 를 넣어 `게임/마인크래프트` 처럼 하위 문서를 만들 수 있습니다. 제목에는 `[ ] | #` 를 쓸 수 없습니다.

문법은 [[문법 도움말]]에서 확인하세요. 돌아가기: [[대문]]
