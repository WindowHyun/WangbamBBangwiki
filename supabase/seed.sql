## 프로필 상자

인물·작품·단체 문서 오른쪽 위에 사진과 정보를 표로 보여 주는 상자입니다. 편집 화면에서 **삽입 → 프로필 상자**를 누르면 입력 창이 열리고, 만든 상자를 누르면 다시 고칠 수 있습니다. 직접 쓰려면 아래 형식을 씁니다.

```
:::infobox
title: 홍길동
image: https://example.com/사진.jpg
caption: 사진 설명
# 기본 정보
본명 | 홍길동
소속 | [[왕밤빵 팀]]
:::
```

- `title` · `image` · `caption` 은 맨 위에 쓰고, 그 아래는 한 줄에 항목 하나(`항목 | 내용`)입니다.
- `# 제목` 줄은 구분 제목이 되고, 내용에는 `[[문서 링크]]` 와 **굵게** 를 쓸 수 있습니다.
- 사진 주소는 `https://` 로 시작해야 합니다.

