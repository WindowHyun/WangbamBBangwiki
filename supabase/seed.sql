## 개요

이 위키는 누구나 로그인 없이 문서를 읽고 고칠 수 있는 위키입니다. 문서는 마크다운 문법으로 작성합니다.

## 문서 찾기

1. 위쪽 검색창에 제목을 입력하면 자동완성이 나타납니다.
2. 제목이 정확히 일치하면 해당 문서로 바로 이동하고, 아니면 본문까지 검색합니다.
3. [[대문]]으로 돌아가거나 **랜덤** 버튼으로 아무 문서나 열어 볼 수 있습니다.

## 문서 고치기

각 문서 오른쪽 위의 **편집** 버튼을 누르면 편집 화면이 열립니다. **미리보기**로 확인한 뒤 **저장**하면 바로 반영됩니다.

### 편집 기록

**역사** 버튼에서 모든 수정 내역을 보고, 두 판의 차이를 비교하거나 이전 판으로 **되돌릴** 수 있습니다. 누군가 먼저 저장한 경우에는 충돌 안내가 나타납니다.

### 역링크와 분류

- **역링크**: 이 문서를 가리키는 다른 문서 목록입니다.
- **분류**: 문서 맨 위 `categories:` 에 적은 이름으로 묶입니다.

